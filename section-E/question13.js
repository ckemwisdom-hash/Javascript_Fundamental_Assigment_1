// Start with an empty array
let marketBasket = [];

// 1. Add items to the end of the array
marketBasket.push("Rice", "Palm Oil", "Onions");

// 2. Remove the last item
marketBasket.pop();

// 3. Add items in the beginning
marketBasket.unshift("Pepper");
marketBasket.unshift("Salt");

// 4. Remove the first item
marketBasket.shift();

// 5. Log the final array
console.log(marketBasket);